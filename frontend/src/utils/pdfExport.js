import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'

export function exportActivitiesToPDF({ activities = [], orgName, orgSpecificId, generatedBy }) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  })

  // Theme Colors
  const primaryOrange = [234, 88, 12] // #ea580c
  const darkSlate = [15, 23, 42]     // #0f172a
  const mutedSlate = [100, 116, 139] // #64748b
  const lightBg = [248, 250, 252]

  // Header Banner
  doc.setFillColor(...darkSlate)
  doc.rect(0, 0, 210, 30, 'F')

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.setTextColor(255, 255, 255)
  doc.text('NeuroForge SDLC Platform', 14, 13)

  doc.setFontSize(9)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(254, 215, 170)
  doc.text('Audit Trail & Recent Activity Report', 14, 21)

  const dateStr = new Date().toLocaleString()
  doc.setFontSize(8)
  doc.setTextColor(203, 213, 225)
  doc.text(`Generated: ${dateStr}`, 196, 21, { align: 'right' })

  // Organization Meta Box
  doc.setFillColor(...lightBg)
  doc.roundedRect(14, 35, 182, 19, 2, 2, 'F')
  doc.setDrawColor(226, 232, 240)
  doc.roundedRect(14, 35, 182, 19, 2, 2, 'S')

  doc.setFontSize(8)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(...darkSlate)
  doc.text('ORGANIZATION:', 18, 42)
  doc.setFont('helvetica', 'normal')
  doc.text(orgName || 'NeuroForge Enterprise', 46, 42)

  doc.setFont('helvetica', 'bold')
  doc.text('ORG SPECIFIC ID:', 18, 49)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(...primaryOrange)
  doc.text(orgSpecificId || 'N/A', 46, 49)

  doc.setFont('helvetica', 'bold')
  doc.setTextColor(...darkSlate)
  doc.text('GENERATED BY:', 115, 42)
  doc.setFont('helvetica', 'normal')
  doc.text(generatedBy || 'Org Admin', 143, 42)

  doc.setFont('helvetica', 'bold')
  doc.text('TOTAL EVENTS:', 115, 49)
  doc.setFont('helvetica', 'normal')
  doc.text(`${activities.length} activity item(s)`, 143, 49)

  // Activities Table
  const tableData = activities.map((act, index) => {
    const formattedDate = act.createdAt
      ? new Date(act.createdAt).toLocaleString(undefined, {
          year: 'numeric',
          month: 'short',
          day: 'numeric',
          hour: '2-digit',
          minute: '2-digit',
        })
      : '—'

    return [
      (index + 1).toString(),
      formattedDate,
      act.action || 'Activity',
      act.actorEmail || 'System',
      act.details || '—',
    ]
  })

  autoTable(doc, {
    startY: 59,
    head: [['#', 'Timestamp', 'Action / Event', 'Actor', 'Details & Metadata']],
    body: tableData,
    theme: 'striped',
    headStyles: {
      fillColor: primaryOrange,
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 8,
      cellPadding: 3,
    },
    bodyStyles: {
      fontSize: 8,
      cellPadding: 2.5,
      textColor: darkSlate,
    },
    alternateRowStyles: {
      fillColor: [255, 247, 237],
    },
    columnStyles: {
      0: { cellWidth: 10, halign: 'center' },
      1: { cellWidth: 35 },
      2: { cellWidth: 42, fontStyle: 'bold' },
      3: { cellWidth: 38 },
      4: { cellWidth: 57 },
    },
    margin: { left: 14, right: 14, bottom: 20 },
    didDrawPage: (data) => {
      const pageCount = doc.internal.getNumberOfPages()
      doc.setFontSize(8)
      doc.setTextColor(...mutedSlate)
      doc.text(
        `Confidential Audit Document · Page ${data.pageNumber} of ${pageCount}`,
        14,
        290
      )
      doc.text(
        'NeuroForge Secure SDLC Platform',
        196,
        290,
        { align: 'right' }
      )
    },
  })

  const safeOrgName = (orgName || 'organization').toLowerCase().replace(/[^a-z0-9]/g, '_')
  const fileDate = new Date().toISOString().split('T')[0]
  doc.save(`NeuroForge_Activities_${safeOrgName}_${fileDate}.pdf`)
}
